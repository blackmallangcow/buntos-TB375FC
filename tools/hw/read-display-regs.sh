# TB375FC: LK가 화면을 켠 뒤의 레지스터를 읽기만 한다. 체크리스트 9절 2c 2차의 0단계다.
# 전원이나 클럭이 꺼진 블록을 읽으면 버스가 멈춘다. mmpll의 사용자가 없는 커널에서 UFS가 클럭을 내린 뒤면
# 화면 블록과 mipitx가 그렇다. framebuffer0의 clocks로 mmpll을 잡아 둔 커널에서 돌린다(6.2절).
# 사용법: read-display-regs.sh > regs.txt   (busybox devmem이 있어야 한다)
set -u
rd() { printf '%s 0x%08x %s\n' "$1" "$2" "$(busybox devmem "$2" 32)"; }
blk() { # 이름 시작 오프셋...
	name=$1; base=$2; shift 2
	for o in "$@"; do rd "$name" $((base + o)); done
}
# 사용자가 없는 mmpll이면 이미 꺼졌을 수 있어 읽지 않는다. 클럭 드라이버가 없는 커널에는 이 파일이 없다
f=/sys/kernel/debug/clk/mmpll/clk_prepare_count
if [ -e "$f" ] && [ "$(cat "$f")" = 0 ]; then
	echo "mmpll has no user: not reading, the bus may hang" >&2
	exit 1
fi
# 전원은 SPM의 PWR_CON으로 본다(ACK bit 30, 31). HW voter의 EN은 LK가 넘길 때부터 0이라 쓸 수 없다(실측).
# 0xe9c~0xea8이 DIS0, DIS1, OVL0, OVL1인 것은 벤더 표에 없고, MDP(0xe94, 0xe98) 다음 자리로 본 것이다
pwr() { busybox devmem $(( 0x1c001000 + $1 )) 32; }
echo "PWR_CON DIS0 $(pwr 0xe9c) DIS1 $(pwr 0xea0) OVL0 $(pwr 0xea4) OVL1 $(pwr 0xea8) MM_INFRA? $(pwr 0xeac)"
on() { [ $(( $(pwr "$1") >> 30 & 3 )) = 3 ]; }
# 클럭이 닫힌 블록도 읽으면 멈춘다. 게이트 칸 CG_CON0(0x100)의 비트가 0일 때만 읽는 블록에 쓴다
gate_open() { [ $(( $(busybox devmem $(( $1 + 0x100 )) 32) >> $2 & 1 )) = 0 ]; }

DISP="0x008 0x034 0x0f4 0x0f8 0x170 0x174 0xc30 0xe90 0xea4 0xeac 0xf0c 0xf48 0xf4c 0xf5c 0xf60 0xf68 0xf74 0xf98 0xfa4"
OVLS="0x008 0x0f0 0x100 0xf00 0xf08 0xf0c 0xf10 0xf14 0xf18 0xf1c 0xf20 0xf38 0xf3c 0xf40 0xf44"
# 블록 사이 신호의 VALID, READY(벤더의 MT6897 진단 칸). 프레임이 안 돌 때 어디서 막혔는지 본다
DISPDBG="0xc00 0xc04 0xc08 0xc0c 0xc10 0xc14 0xc18 0xc1c 0xc20 0xc24 0xc28 0xc2c"
# 0번 뮤텍스 전부와, 다른 번호가 켜져 있는지 보는 EN 칸(0x20 간격)
MUTEX="0x08 0x20 0x24 0x2c 0x30 0x34 0x40 0x60 0x80 0xa0 0xc0 0xe0 0x100"
OVL="0x0c 0x20 0x24 0x2c 0x30 0x38 0x3c 0x44 0xf40 0xf4c 0xc8 0xd0 0x1e0 0x1f8 0x1fc 0x20c 0x324 0x740"
DSC="0x00 0x14 0x18 0x1c 0x20 0x24 0x28 0x2c 0x30 0x34 0x38 0x3c 0x60 0x70 0x80 0x84 0x88 0x8c 0x90 0x94 0x98 0x9c 0xa0 0xa4 0xa8 0xac 0xb0 0xb4 0xb8 0xbc 0xc0 0xc4 0xc8 0xcc 0x200 0x228"
DSI="0x00 0x08 0x10 0x14 0x18 0x1c 0x20 0x24 0x28 0x2c 0x38 0x50 0x54 0x58 0x60 0x64 0xf0 0x100 0x104 0x108 0x110 0x114 0x118 0x11c 0x170 0x200 0x400 0x404 0x410 0x414 0x418 0x424 0x428 0x42c 0x430 0x434 0x438 0xc00"
# 레인 트림은 4개 블록의 0x100, 0x108, 0x1c4, 0x1c8부터 0x100 간격이다
PHY="0x04 0x08 0x0c 0x28 0x2c 0x30 0x3c 0x40 0x50 0x320 0x100 0x108 0x1c4 0x1c8"
# 라브의 MMU 비트(SMI_LARB_NONSEC_CON). LK는 라브0·1의 16칸을 지운다. 1이면 OVL의 주소가 IOMMU를 지난다
LARB="0x380 0x384 0x388 0x38c 0x390 0x394 0x398 0x39c 0x3a0 0x3a4 0x3a8 0x3ac 0x3b0 0x3b4 0x3b8 0x3bc"

if on 0xe9c; then
	blk dispsys0 0x14000000 $DISP $DISPDBG
	blk mutex0 0x14001000 $MUTEX
	blk dsc0 0x1400c000 $DSC
	blk dsi0 0x1400d000 $DSI
fi
if on 0xea0; then
	blk dispsys1 0x14200000 $DISP $DISPDBG
	blk mutex1 0x14201000 $MUTEX
	blk dsc1 0x1420c000 $DSC
	blk dsi1 0x1420d000 $DSI
fi
if on 0xea4; then
	blk ovlsys0 0x14400000 $OVLS
	blk ovlmutex0 0x14401000 $MUTEX
	blk ovl0 0x14402000 $OVL
	# LK는 OVL 셋을 사슬로 잇는다. 그림의 레이어가 어느 OVL에 있는지 본다
	gate_open 0x14400000 5 && blk ovl0_chain1 0x14403000 $OVL
	gate_open 0x14400000 6 && blk ovl0_chain2 0x14404000 $OVL
	# 라브의 클럭은 CLK_OVLSYS0_SMI_SUB_COMMON0(순정 트리)이다
	if gate_open 0x14400000 24; then
		blk larb0 0x1440c000 $LARB
		blk larb1 0x1440d000 $LARB
	fi
fi
if on 0xea8; then
	blk ovlsys1 0x14600000 $OVLS
	blk ovlmutex1 0x14601000 $MUTEX
	blk ovl1 0x14602000 $OVL
	gate_open 0x14600000 5 && blk ovl1_chain1 0x14603000 $OVL
	gate_open 0x14600000 6 && blk ovl1_chain2 0x14604000 $OVL
	if gate_open 0x14600000 24; then
		blk larb20 0x1460c000 $LARB
		blk larb21 0x1460d000 $LARB
	fi
fi
blk mipitx0 0x11e50000 $PHY
blk mipitx1 0x11e60000 $PHY
